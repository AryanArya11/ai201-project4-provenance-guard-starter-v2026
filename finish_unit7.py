import json
from pathlib import Path

AI_TEXT = (
    'Learning a new programming language requires consistent practice and a structured approach. '
    'Students should begin by understanding basic concepts such as variables, loops, and functions. '
    'They can then apply these concepts through small projects that gradually increase in complexity. '
    'Regular practice helps reinforce knowledge and improve problem-solving skills. '
    'By reviewing mistakes and seeking feedback, students can develop confidence and become more effective programmers.'
)
EDITED_AI_TEXT = (
    'Learning a new programming language takes practice. A lot of it, honestly. '
    'Start with variables, loops, and functions, then try building something small. '
    'You will probably get stuck, but that is part of figuring it out. '
    'As the projects get harder, go back and look at what went wrong. '
    'Getting feedback helps too. I think that makes learning feel less overwhelming.'
)


def paragraph(prompt):
    print(prompt)
    while True:
        text = input('Paste ONE paragraph on ONE line, then press Enter: ').strip()
        if len(text.split()) >= 30:
            return text
        print('Please use at least 30 words so the signals have enough text.')


def main(root=None):
    root = Path(root) if root is not None else Path(__file__).resolve().parent
    if not (root / 'app.py').exists():
        raise SystemExit('Save this script in the project folder beside app.py, then run it again.')
    print('Read the five targets in criteria.md first. The large evaluation sets are for Unit 8.')
    if input('Do you agree with all five targets and reasons? Type yes to keep them: ').strip().lower() != 'yes':
        raise SystemExit('Edit criteria.md with your own targets and reasons, then run this script again.')
    casual = paragraph('\nUse an existing casual paragraph YOU wrote, such as a reflection. Do not use AI-written text.')
    formal = paragraph('\nUse an existing formal paragraph YOU wrote, such as an essay paragraph. Do not use AI-written text.')
    if casual == formal:
        raise SystemExit('Use two different paragraphs, then run the script again.')
    samples = [
        {'name': 'Unedited AI', 'source': 'Generated by ChatGPT for calibration', 'text': AI_TEXT},
        {'name': 'Plain human', 'source': 'User reports writing this paragraph independently', 'text': casual},
        {'name': 'Formal human', 'source': 'User reports writing this paragraph independently', 'text': formal},
        {'name': 'Lightly edited AI', 'source': 'AI-origin paragraph edited by ChatGPT; not a human-written control', 'text': EDITED_AI_TEXT},
    ]
    from app import app
    import scoring
    client = app.test_client()
    rows = []
    for index, sample in enumerate(samples, 1):
        print(f"Scoring {index}/4: {sample['name']} (the first call loads GPT-2)...", flush=True)
        response = client.post('/submit', json={'text': sample['text'], 'creator_id': f'unit7-calibration-{index}'})
        if response.status_code != 200:
            raise SystemExit(f'{sample["name"]} failed: HTTP {response.status_code}, {response.get_json()}. No completion write-up was generated.')
        rows.append({**sample, 'http_status': response.status_code, **response.get_json()})
    results = root / 'results'
    results.mkdir(exist_ok=True)
    (root / 'calibration_inputs.json').write_text(json.dumps(samples, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    (results / 'calibration.json').write_text(json.dumps(rows, indent=2, ensure_ascii=False) + '\n', encoding='utf-8')
    table = ['| Sample | Model | Style | Combined | Label |', '|---|---:|---:|---:|---|']
    for row in rows:
        table.append(f"| {row['name']} | {row['model_score']:.4f} | {row['style_score']:.4f} | {row['confidence']:.4f} | {row['guess']} |")
    observed = {row['guess'] for row in rows}
    missing = {'ai', 'human', 'unsure'} - observed
    coverage = ('All three labels appeared on actual text submissions.' if not missing else
                'These four texts did not produce every label. Missing: ' + ', '.join(sorted(missing)) + '. Real-text label coverage has not been demonstrated yet.')
    split = [row for row in rows if abs(row['model_score'] - row['style_score']) > 0.50]
    if split:
        row = split[0]
        disagreement = (f"The signals strongly disagreed on {row['name']}: model {row['model_score']:.4f}, "
                        f"style {row['style_score']:.4f}. The combining rule returned {row['confidence']:.4f}, "
                        f"which received the {row['guess']} label. I feel like keeping a strong disagreement "
                        'in the unsure range is more reasonable than making a confident accusation.')
    else:
        row = max(rows, key=lambda item: abs(item['model_score'] - item['style_score']))
        disagreement = (f"The largest signal difference was on {row['name']}: model {row['model_score']:.4f}, "
                        f"style {row['style_score']:.4f}. The combined score was {row['confidence']:.4f}, "
                        f"with the {row['guess']} label. None of these four inputs crossed the 0.50 strong-disagreement cutoff.")
    report = ('### Actual four-text calibration\n\n'
              'I ran all four samples through `POST /submit` using real local GPT-2 and the style signal. '
              'I supplied the two human paragraphs from my own writing. ChatGPT generated the AI sample '
              'and the edited AI sample. The full inputs and responses are in `results/calibration.json`, '
              'and the decisions are in `logs/audit.jsonl`.\n\n' + '\n'.join(table) + '\n\n' +
              disagreement + '\n\n' + coverage + '\n\n'
              'This is a small calibration run, so I am not calling it an accuracy evaluation. '
              'The larger fixed-set false-positive and score-gap targets still need the Unit 8 evaluation.\n')
    (results / 'calibration.md').write_text(report, encoding='utf-8')
    readme_path = root / 'README.md'
    readme = readme_path.read_text(encoding='utf-8')
    # Update stale environment limitations while preserving the actual Sample Run.
    old = 'The full GPT-2 run could not be completed here because package/model downloads were blocked.'
    if old in readme:
        start = readme.index(old)
        end = readme.index('## Label Variants', start)
        readme = readme[:start] + report + '\n' + readme[end:]
    else:
        marker = '## Label Variants'
        if marker not in readme:
            raise SystemExit('Calibration results saved, but README layout differs. Paste results/calibration.md into Signals and Scoring manually.')
        begin = '<!-- ACTUAL_CALIBRATION_START -->'
        end_marker = '<!-- ACTUAL_CALIBRATION_END -->'
        if begin in readme and end_marker in readme:
            before, rest = readme.split(begin, 1)
            _, after = rest.split(end_marker, 1)
            readme = before + begin + '\n' + report + end_marker + after
        else:
            readme = readme.replace(marker, begin + '\n' + report + end_marker + '\n\n' + marker, 1)
    readme = readme.replace('I have not independently rewritten the five targets yet.',
                            'I reviewed the five targets after the initial real-model sample run.')
    readme = readme.replace('I still need to review the criteria and inspect real model outputs before calling the project fully verified.',
                            'I reviewed the criteria and inspected real model outputs. The calibration results above show what was and was not demonstrated.')
    readme_path.write_text(readme, encoding='utf-8')
    criteria_path = root / 'criteria.md'
    criteria = criteria_path.read_text(encoding='utf-8')
    criteria = criteria.replace('**AI-assisted draft, written before implementation or scoring runs. Aryan needs to review these targets before submitting.**',
                                '**AI-assisted criteria. ChatGPT drafted these targets before implementation or scoring runs. I reviewed and accepted them after the initial real-model sample run.**')
    criteria_path.write_text(criteria, encoding='utf-8')
    print('\n' + '\n'.join(table))
    print('\n' + coverage)
    print('\nSaved calibration evidence and updated README.md and criteria.md. No targets or thresholds were changed.')
    if missing:
        print('NEXT: Paste this table into ChatGPT before submitting; label coverage still needs attention.')
    else:
        print('NEXT: Inspect the updated README, then commit and push the evidence.')


if __name__ == '__main__':
    main()
